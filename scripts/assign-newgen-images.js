/**
 * Assigns one local photo to every new-generation product (scripts/newgen-catalog.js)
 * and writes scripts/newgen-images.js ({ productId: 'assets/newgen/....jpg' }).
 *
 * Products draw from the bucket matching their type first, then the lifestyle
 * "model" bucket, always an image that is not already used by an existing page.
 * Run after scripts/download-newgen-images.js.
 */
const fs = require('fs');
const path = require('path');
const catalog = require('./newgen-catalog');
const buckets = require('./newgen-image-buckets');

const PUB = path.join(__dirname, '..', 'public');
const OUT = path.join(__dirname, 'newgen-images.js');

const TYPE_BUCKETS = {
    jacket: ['jacket', 'model'],
    jeans: ['jeans', 'model'],
    hoodie: ['hoodie', 'model'],
    tee: ['tee', 'model'],
    pants: ['pants', 'model'],
    knit: ['knit', 'model'],
    shirt: ['shirt', 'model'],
    shoe: ['shoe', 'model'],
    hat: ['hat', 'model'],
    bag: ['bag', 'model'],
    accessory: ['accessory', 'model'],
};

// Images already used anywhere on the site must stay unique to their product.
const corpus = fs.readdirSync(PUB).filter(f => f.endsWith('.html'))
    .map(f => fs.readFileSync(path.join(PUB, f), 'utf8')).join('\n');
const taken = new Set([...corpus.matchAll(/assets\/[A-Za-z0-9_\-./]+/g)].map(m => m[0]));

const cursor = {};
const pick = type => {
    for (const bucket of TYPE_BUCKETS[type] || ['model']) {
        const list = (buckets[bucket] || []).filter(img => !taken.has(img));
        if (!list.length) continue;
        const i = (cursor[bucket] || 0) % list.length;
        cursor[bucket] = i + 1;
        const img = list[i];
        taken.add(img);
        return img;
    }
    return null;
};

const images = {};
const missing = [];
for (const p of catalog) {
    if (p.image) { taken.add(p.image); images[p.id] = p.image; continue; }
    const img = pick(p.type);
    if (!img) missing.push(`${p.id} (${p.type})`);
    else images[p.id] = img;
}

if (missing.length) {
    console.error('No image available for:\n  ' + missing.join('\n  '));
    process.exit(1);
}

fs.writeFileSync(OUT,
    '// Generated by scripts/assign-newgen-images.js — product id -> local image.\nmodule.exports = ' +
    JSON.stringify(images, null, 2) + ';\n');

const used = Object.values(images);
console.log(`assigned ${used.length} images (${new Set(used).size} unique)`);
console.log('per type:', JSON.stringify(catalog.reduce((m, p) => (m[p.type] = (m[p.type] || 0) + 1, m), {})));
