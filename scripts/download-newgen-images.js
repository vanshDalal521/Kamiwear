// Downloads harvested Openverse candidates into public/assets/newgen/, grouped
// into type buckets. Keeps the best-sized files per bucket and records what was
// saved in scripts/newgen-image-buckets.js (bucket -> [file, ...]).
const fs = require('fs');
const path = require('path');

const STAGE = '/private/var/folders/t6/1ph1_bw9039gk0349_hh6jnc0000gn/T/opencode/newgen-raw';
const META = path.join(STAGE, 'meta.json');
const OUT = path.join(__dirname, '..', 'public', 'assets', 'newgen');
const BUCKET_FILE = path.join(__dirname, '..', 'scripts', 'newgen-image-buckets.js');
const sleep = ms => new Promise(r => setTimeout(r, ms));

// Which harvest bucket each query feeds.
const BUCKETS = {
    'jeans blue denim': 'jeans', 'wide leg jeans': 'jeans', 'distressed jeans': 'jeans',
    'bomber jacket': 'jacket', 'puffer jacket': 'jacket', 'windbreaker jacket': 'jacket',
    'leather jacket': 'jacket', 'varsity jacket': 'jacket', 'denim jacket': 'jacket',
    'corduroy jacket': 'jacket',
    'sweatshirt': 'hoodie', 'oversized hoodie': 'hoodie', 'hoodie sweatshirt': 'hoodie',
    'hoodie portrait': 'hoodie',
    'black t-shirt': 'tee', 'graphic t-shirt': 'tee', 'crop top fashion': 'tee',
    'long sleeve shirt': 'tee',
    'tracksuit': 'pants', 'cargo pants': 'pants', 'jogger pants': 'pants',
    'cargo pants pockets': 'pants', 'wide leg trousers': 'pants', 'corduroy pants': 'pants',
    'denim shirt': 'shirt', 'flannel shirt': 'shirt', 'long sleeve shirt': 'shirt',
    'knit sweater': 'knit',
    'sneakers shoes': 'shoe', 'white sneakers': 'shoe', 'high top sneakers': 'shoe',
    'ankle boots': 'shoe', 'canvas shoes': 'shoe',
    'baseball cap': 'hat', 'bucket hat': 'hat', 'beanie hat': 'hat',
    'canvas backpack': 'bag', 'tote bag canvas': 'bag', 'backpack bag': 'bag',
    'crossbody bag': 'bag', 'tote bag': 'bag',
    'belt fashion': 'accessory', 'sunglasses fashion': 'accessory',
    'fashion necklace': 'accessory', 'leather belt': 'accessory', 'scarf fashion': 'accessory',
    'young woman fashion pose': 'model', 'urban fashion model': 'model',
    'street fashion portrait': 'model', 'hoodie portrait': 'model',
    'skater fashion outfit': 'model', 'streetwear fashion': 'model',
};

// How many files each product type may draw from.
const NEEDED = { jacket: 20, jeans: 14, hoodie: 16, tee: 20, pants: 15, knit: 8, shirt: 8, shoe: 8, hat: 8, bag: 8, accessory: 6, model: 24 };

const looksLikeImage = buf =>
    buf.length > 20000 &&
    ((buf[0] === 0xff && buf[1] === 0xd8) || (buf[0] === 0x89 && buf[1] === 0x50) ||
        (buf[0] === 0x52 && buf[1] === 0x49) || buf.toString('ascii', 0, 4) === 'RIFF');

(async () => {
    const meta = JSON.parse(fs.readFileSync(META, 'utf8'));
    fs.mkdirSync(OUT, { recursive: true });

    const buckets = {};
    if (fs.existsSync(BUCKET_FILE)) Object.assign(buckets, require(BUCKET_FILE));
    const have = new Set(Object.values(buckets).flat());
    const URL_FILE = path.join(__dirname, 'newgen-downloaded-urls.json');
    const done = new Set(fs.existsSync(URL_FILE) ? JSON.parse(fs.readFileSync(URL_FILE, 'utf8')) : []);

    for (const cand of meta) {
        const bucket = BUCKETS[cand.query];
        if (!bucket) continue;
        if (done.has(cand.url)) continue;
        const target = NEEDED[bucket] || 8;
        if ((buckets[bucket] || []).length >= target) continue;

        const slug = cand.query.replace(/[^a-z0-9]+/gi, '-').toLowerCase();
        const file = `${bucket}-${slug}-${Math.random().toString(36).slice(2, 7)}.jpg`;
        const dest = path.join(OUT, file);
        try {
            const res = await fetch(cand.url, { headers: { 'User-Agent': 'kamiwear-catalog/1.0' }, signal: AbortSignal.timeout(25000) });
            if (!res.ok) continue;
            const buf = Buffer.from(await res.arrayBuffer());
            if (!looksLikeImage(buf)) continue;
            fs.writeFileSync(dest, buf);
            done.add(cand.url);
            if (have.has('assets/newgen/' + file)) continue;
            (buckets[bucket] = buckets[bucket] || []).push('assets/newgen/' + file);
            have.add('assets/newgen/' + file);
            cand.file = file;
        } catch (e) { /* skip failed download */ }
        await sleep(250);
    }

    fs.writeFileSync(URL_FILE, JSON.stringify([...done], null, 1));
    fs.writeFileSync(BUCKET_FILE, '// Generated by scripts/download-newgen-images.js — bucket -> local image paths.\nmodule.exports = ' +
        JSON.stringify(buckets, null, 2) + ';\n');

    const counts = Object.fromEntries(Object.entries(buckets).map(([k, v]) => [k, v.length]));
    console.log('buckets:', JSON.stringify(counts));
    const short = Object.entries(NEEDED).filter(([t, n]) => (counts[t] || 0) < n);
    if (short.length) console.log('SHORT:', short.map(([t, n]) => `${t}=${counts[t] || 0}/${n}`).join(', '));
})();
